#!/usr/bin/env python3
"""Appendix table: the 30-venture reference set on one portrait page.

One numbered, two-line block per venture: a hand-written one-line summary with
the pseudonymized URL beneath it, a stacked Goal/Raised money cell, and a
stacked Start/End dates cell.  Rows follow the evaluator ranking
(analysis/evalrank-30.csv); the bottom half is the seed set.  Writes
figs/reference-set.tex (the tabular body; the manuscript wraps it in a float).

Usage: python3 analysis/build_universe_table.py
"""
