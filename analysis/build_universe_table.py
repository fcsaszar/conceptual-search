def tex_escape(s):
    s = (s.replace("\\", "").replace("&", "\\&").replace("%", "\\%")
          .replace("#", "\\#").replace("_", "\\_").replace("$", "\\$"))
    # typographic quotes: "..." -> ``...'' (single quotes in the gists are
    # apostrophes, which LaTeX already sets correctly)
    while '"' in s:
        s = s.replace('"', "``", 1).replace('"', "''", 1)
    return s


def fmt_money(x):
    return f"\\${int(round(float(x))):,}"


def fmt_date(s):
    return date.fromisoformat(s).strftime("%b~%-d")


def main():
    csv.field_size_limit(10**9)
    rows = {r["id"]: r for r in csv.DictReader(open(BASE / "in" / "projects.csv",
                                                    encoding="utf-8-sig"))}
    rank = list(csv.DictReader(open(BASE / "analysis" / "evalrank-30.csv")))
    order = [r["id"] for r in rank]
    perf = {r["id"]: float(r["universe_win_rate"]) for r in rank}
    missing = set(rows) - set(GIST)
    assert not missing, f"gists missing for: {missing}"

    # Column widths fill \textwidth exactly.  The unlabeled rank column uses a
    # fixed narrow width, and the summary column absorbs the remainder.
    summary_w = ("\\dimexpr\\textwidth-0.4cm-0.35em-2.2cm-1.5cm-1.2cm"
                 "-6\\tabcolsep\\relax")
    lines = [
        "% Auto-generated by analysis/build_universe_table.py; do not edit.",
        f"\\begin{{tabular}}{{@{{}}>{{\\raggedleft\\arraybackslash}}p{{0.4cm}}"
        f"@{{\\hspace{{0.35em}}}}p{{2.2cm}}L{{{summary_w}}}"
        ">{\\raggedleft\\arraybackslash}p{1.5cm}p{1.2cm}@{}}",
        "\\toprule",
        " & \\textbf{Venture}\\newline\\textbf{(Performance)} & "
        "\\textbf{Brief summary}\\newline \\textbf{URL} & "
        "\\textbf{Goal}\\par \\textbf{Raised} & "
        "\\textbf{Start}\\newline \\textbf{End} \\\\",
        "\\midrule",
    ]
    for i, vid in enumerate(order):
        if i == 15:
            lines.append("\\addlinespace[1pt]\\midrule\\addlinespace[1pt]")
        r = rows[vid]
        venture = f"\\texttt{{{tex_escape(vid)}}}\\newline ({100*perf[vid]:.1f}\\%)"
        display_url = r["url"].replace("https://", "").replace("http://", "")
        summary = (f"{tex_escape(GIST[vid])}\\newline"
                   f"\\adjustbox{{max width=\\linewidth}}{{\\href{{{r['url']}}}"
                   f"{{\\fontsize{{5}}{{5.8}}\\selectfont {display_url}}}}}")
        money = f"{fmt_money(r['goal'])}\\par {fmt_money(r['raised'])}"
        dates = f"{fmt_date(r['launch'])}\\newline{{}}{fmt_date(r['deadline'])}"
        lines.append(f"{i + 1} & {venture} & {summary} & {money} & {dates} \\\\"
                     "\\addlinespace[0.25pt]")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (BASE / "figs" / "reference-set.tex").write_text("\n".join(lines) + "\n")
    print(f"wrote figs/reference-set.tex ({len(order)} two-line blocks, "
          "evaluator-rank order, seeds below the rule)")


if __name__ == "__main__":
    main()
